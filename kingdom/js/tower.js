/* Фразы Башни мудреца для озвучки */
function towerPhrases() {
  const uniq = a => [...new Set(a)];
  const qs = uniq(Object.values(TT)
    .concat(Object.values(TQ).flatMap(l => l.map(x => x[0])), Object.values(TF).flatMap(s => s.list.map(x => x[0])), T_COLORQ.map(x => x[0]), T_SHAPEQ.map(x => x[0]), T_CMP.map(x => x[0])));
  const ans = uniq(Object.values(TC).flatMap(l => l.map(x => x[1]))
    .concat(Object.values(TQ).flatMap(l => l.map(x => x[2])), Object.values(TF).flatMap(s => s.opts.map(o => o[1])), Object.values(T_COLORS).map(c => c[1]), Object.values(T_SHAPES).map(s => s[0]), T_CMP.map(x => x[3])));
  return [
    { g: 'Башня мудреца: вопросы', items: qs },
    { g: 'Башня мудреца: ответы', items: ans },
    { g: 'Башня мудреца: сказка', items: Object.values(TSTORY).map(s => s.t) }
  ];
}
