function syllables(cons, vows) {
  const out = [];
  for (const c of cons) for (const v of (vows || 'АОУЫИ')) {
    if (v === 'Ы' && 'ГКЖШХЧЩ'.includes(c)) continue;
    out.push(c + v);
  }
  return out;
}
